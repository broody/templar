"""Generate Cairo/Python interoperability vectors using public synthetic test keys."""
from pathlib import Path
from protocol import *
from encoding import encode_spend, encode_intent
w=Wallet.restore(bytes(range(32)))
n,e=send(w.address,TOKEN,100,rho=7);tree=Tree();tree.insert(n.commitment)
inner,cipher=prepare_return(w.address,0x99,rho=8)
intent=dict(adapter=0xaaa,amount=100,expiry=1000,calldata=[42],
            notes=[dict(note_id=17,token=0x99,minimum=70,inner=inner,ciphertext=cipher)])
digest=execution_hash(CHAIN,POOL,TOKEN,**intent)
case=make_case([(n,w.spend_key,0)],[],[(0xaaa,100)],tree,intent=digest)
validate_case(case)
raw=encode_intent(intent)
arr=lambda values:'array!['+','.join(hex(x) for x in values)+']'
source='''// Synthetic public keys only. Generated by generate_vectors.py.
use pool::statement::verify_spend;
use pool::spend::{Spend, compute_binding};
use pool::return_note::{ExecutionIntent, hash_intent};
'''
source+=f'''fn witness() -> Array<felt252> {{ {arr(case['witness'])} }}
#[test]
fn python_cairo_agree_on_owner_statement_and_execution_intent() {{
    let actual=verify_spend(witness().span());
    assert_eq!(actual,{arr(case['public'])});
    let mut wire={arr(encode_spend(case,[])[:-1])}.span();
    let spend: Spend=Serde::deserialize(ref wire).unwrap(); assert(wire.is_empty(),'SPEND_TRAILING');
    let mut raw={arr(raw)}.span(); let intent: ExecutionIntent=Serde::deserialize(ref raw).unwrap();
    assert(raw.is_empty(),'INTENT_TRAILING');
    assert_eq!(hash_intent(@spend,@intent),{hex(digest)});
    assert_eq!(compute_binding(@spend),*actual.at(7));
}}
#[test]
#[should_panic(expected: ('BINDING',))]
fn tampered_intent_rejected_by_owner_statement() {{
    let mut w=witness(); w[10]=42; verify_spend(w.span());
}}
'''
# Cairo Array indexing cannot mutate in place; rebuild the altered fixture.
bad=list(case['witness']);bad[10]=42
source=source.replace('let mut w=witness(); w[10]=42; verify_spend(w.span());',f'verify_spend({arr(bad)}.span());')
(Path(__file__).parent/'cairo/src/tests/golden.cairo').write_text(source)
print('Generated owner-statement and execution-intent cross-language vectors.')
