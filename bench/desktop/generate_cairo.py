#!/usr/bin/env python3
"""Generate experimental Poseidon2 arithmetic circuit using Garaga's code generator."""
from pathlib import Path
from functools import reduce
from garaga.curves import CurveID,get_base_field
from garaga.modulo_circuit import ModuloCircuit
from garaga.modulo_circuit_structs import u384
from native_reference import DIAG,RC,M
ROOT=Path(__file__).resolve().parent
c=ModuloCircuit(name='desktop_poseidon2',curve_id=CurveID.GRUMPKIN.value,generic_circuit=False,compilation_mode=1)
f=get_base_field(CurveID.GRUMPKIN)
s=[c.write_struct(u384(f'x{i}',[f(i)])) for i in range(4)]
constant=lambda x:c.set_or_get_constant(f(x))
def power5(x):
    xx=c.mul(x,x)
    return c.mul(c.mul(xx,xx),x)
def external(s):
    return [reduce(c.add,[c.mul(constant(k),v) for k,v in zip(row,s)]) for row in M]
s=external(s)
for r in range(64):
    if r<4 or r>=60:
        s=external([power5(c.add(v,constant(RC[4*r+i]))) for i,v in enumerate(s)])
    else:
        s[0]=power5(c.add(s[0],constant(RC[4*r])))
        total=reduce(c.add,s)
        s=[c.add(total,c.mul(v,constant(d))) for v,d in zip(s,DIAG)]
for i,v in enumerate(s): c.extend_struct_output(u384(f'y{i}',[v]))
code,name=c.compile_circuit()
out=ROOT/'cairo/src';out.mkdir(parents=True,exist_ok=True)
code=code.replace('crate::definitions::get_modulus(curve_index)', 'garaga::definitions::get_GRUMPKIN_modulus()')
imports="""use core::circuit::{CircuitElement as CE, CircuitInput as CI, CircuitInputs, CircuitOutputsTrait, EvalCircuitTrait, circuit_add, circuit_mul, u384};
use garaga::core::circuit::AddInputResultTrait2;
"""
(out/'permutation.cairo').write_text('// Generated by generate_cairo.py; benchmark only, not audited.\n'+imports+code)
print(name)
