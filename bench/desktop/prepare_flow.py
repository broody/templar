#!/usr/bin/env python3
"""Bind wallet fixtures to addresses from the deterministic Cairo setup test."""
from pathlib import Path
import re,json
from fixtures import make
ROOT=Path(__file__).resolve().parent
m=re.search(r'BENCH_CONTEXT (\d+) (\d+) (\d+) (\d+)',(ROOT/'results/context.log').read_text())
assert m,'Run the export_context Cairo test first'
p=make('native',*map(int,m.groups()))
text='// Public ledger data only; generated by prepare_flow.py.\n'
text+=f'pub const EXPECTED_POOL: felt252 = {p["pool"]};\npub const EXPECTED_TOKEN: felt252 = {p["token"]};\n'
for i,dep in enumerate(p['deposits']):text+=f'pub const INNER_{i}: u256 = {dep["inner"]};\n'
for who in ['alice','bob']:
 text+=f'pub const {who.upper()}_ROOT: u256 = {p[who]["root"]};\n'
 for name in ['nullifiers','outputs']:
  values=p[who][name]
  text+=f'pub const {who.upper()}_{name.upper()}: [u256; {len(values)}] = [{",".join(map(str,values))}];\n'
(ROOT/'cairo/src/flow_data.cairo').write_text(text)
print(json.dumps({k:p[k] for k in ['chain','pool','token','recipient']}))
