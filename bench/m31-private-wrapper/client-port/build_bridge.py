"""Build the circuit-A Cairo bridge and account from circuit A's trusted build manifest.

Vendor source is copied from the reviewed optimized bridge (checked M31 inversion);
originals are untouched. Only the two topology files are regenerated, by the existing
generator. Never run this with a manifest supplied by an untrusted proof producer.
"""
from pathlib import Path
import hashlib, importlib.util, json, shutil, subprocess, sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
VENDOR = ROOT / 'target/m31-private-wrapper/optimized-cairo/vendor'
CLIENT = ROOT / 'bench/m31-private-blake/client/src'
SCARB = '/home/broody/.asdf/installs/scarb/2.18.0/bin/scarb'
DOMAIN = b'Templar-private-membership-BLAKE2S-v1'


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def ro(tag, parts):
    h = hashlib.blake2s(digest_size=32)
    h.update(DOMAIN)
    h.update(len(tag).to_bytes(8, 'little'))
    h.update(tag)
    h.update(len(parts).to_bytes(8, 'little'))
    for p in parts:
        h.update(len(p).to_bytes(8, 'little'))
        h.update(p)
    return h.digest()


def statement_prefix():
    """MAGIC || ro("circuit", client sources), as in proof::public_bytes."""
    files = ['air.rs', 'hash.rs', 'constants.rs', 'poly.rs', 'crypto.rs', 'proof.rs']
    return b'TMPZK002' + ro(b'circuit', [(CLIENT / f).read_bytes() for f in files])


def main():
    manifest_path = Path(sys.argv[1]).resolve()
    work = Path(sys.argv[2]).resolve()
    assert not work.exists(), 'fresh work directory required'
    manifest = json.loads(manifest_path.read_text())
    assert manifest['purpose'] == 'tmpzk002-client-verifier-circuit'
    assert manifest['n_outputs'] == 17
    shutil.copytree(HERE / 'cairo', work)
    shutil.copytree(VENDOR, work / 'vendor')
    spec = importlib.util.spec_from_file_location('trusted_generator', ROOT / 'bench/direct-air/cairo/generate_constants.py')
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    # The generator's checks are unchanged; supply the fixed facts of prove_circuit.rs.
    adapted = dict(manifest, purpose='synthetic-diagnostic', channel='Blake2sMerkleChannel',
                   merkle_hasher='Blake2sMerkleHasher', output_addresses=list(range(3, 3 + 17)), u_address=2)
    generated = gen.generate(adapted)
    for name, text in generated.items():
        (work / 'vendor' / name).write_text(text.replace('trusted synthetic circuit', 'trusted TMPZK002 circuit-A'))
    prefix = statement_prefix()
    consts = ('// Generated by build_bridge.py: MAGIC || ro("circuit", client sources).\n'
              'pub fn statement_prefix() -> Array<u8> {\n    array![' + ', '.join(map(str, prefix)) + ']\n}\n')
    (work / 'bridge/src/statement_consts.cairo').write_text(consts)
    record = {
        'trusted_manifest_sha256': sha(manifest_path),
        'statement_prefix_hex': prefix.hex(),
        'client_sources': {f.name: sha(f) for f in sorted(CLIENT.glob('*.rs'))},
        'vendor_source': str(VENDOR),
        'generated_files': {n: sha(work / 'vendor' / n) for n in generated},
        'template_files': {str(p.relative_to(HERE)): sha(p) for p in sorted((HERE / 'cairo').rglob('*')) if p.is_file()},
    }
    (work / 'build-record.json').write_text(json.dumps(record, indent=2) + '\n')
    subprocess.run([SCARB, '--manifest-path', str(work / 'Scarb.toml'), 'build', '-p', 'templar_membership_bridge'], check=True)
    subprocess.run([SCARB, '--manifest-path', str(work / 'Scarb.toml'), 'test', '-p', 'templar_membership_bridge'], check=True)
    subprocess.run([SCARB, '--profile', 'contract', '--manifest-path', str(work / 'Scarb.toml'), 'build', '-p', 'templar_membership_account'], check=True)
    print(json.dumps({'work': str(work), 'statement_prefix_hex': prefix.hex()}))


if __name__ == '__main__':
    main()
