"""Build the arithmetic-profile client bridge and account.

The five Cairo verifier crates are copied from the fork (broody/proving, branch
templar/arithmetic-profile), whose `circuit_air` skips absent components and rejects their
nonzero claimed sums. Generated files: both GENERATED sections for the manifest's shape
(examples/gen_cairo_consts.rs) and the circuit hash pin. Never run this with a manifest from an
untrusted producer.
"""
from pathlib import Path
import hashlib, json, shutil, subprocess, sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
FORK = ROOT / 'target/proving-arith'
UPSTREAM = FORK / 'stwo_cairo_verifier/crates'
CRATES = ['bounded_int', 'constraint_framework', 'verifier_core', 'verifier_utils', 'circuit_air']
SCARB = '/home/broody/.asdf/installs/scarb/2.18.0/bin/scarb'


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    manifest_path = Path(sys.argv[1]).resolve()
    work = Path(sys.argv[2]).resolve()
    assert not work.exists(), 'fresh work directory required'
    m = json.loads(manifest_path.read_text())
    # Membership (8 outputs) or R0 payment (23 outputs): template and message tag per purpose.
    template, tag, n_outputs = {
        'tmpzsa-client-membership': ('cairo-arith', 'TMPZSA01_MEMBERSHIP_V1', 8),
        'tmpzr0-client-payment': ('cairo-r0', 'TMPZR0_PAYMENT_V3', 32),
    }[m['purpose']]
    assert m['n_outputs'] == n_outputs
    logs = m['component_log_sizes']
    assert logs[0] > 0 and logs[1] > 0 and all(l == 0 for l in logs[2:]), 'arithmetic profile'
    fri = m['fri_config']
    assert {k: fri[k] for k in ('log_last_layer_degree_bound', 'fold_step')} == {'log_last_layer_degree_bound': 0, 'fold_step': 4}
    assert fri['pow_bits'] + fri['log_blowup_factor'] * fri['n_queries'] >= 96, 'FRI security below 96 bits'
    fork_commit = subprocess.run(['git', '-C', str(FORK), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    dirty = subprocess.run(['git', '-C', str(FORK), 'status', '--porcelain', 'stwo_cairo_verifier'], capture_output=True, text=True, check=True).stdout
    assert not dirty, 'fork Cairo verifier has uncommitted changes'
    shutil.copytree(HERE / template, work, ignore=shutil.ignore_patterns('target'))
    for c in CRATES:
        shutil.copytree(UPSTREAM / c, work / 'vendor' / c, ignore=shutil.ignore_patterns('target'))
    subprocess.run([str(HERE / 'target/release/examples/gen_cairo_consts'), str(manifest_path),
                    str(work / 'vendor/circuit_air/src')], check=True)
    consts = work / 'vendor/circuit_air/src/multiverifier_consts.cairo'
    text = consts.read_text()
    assert text.count('pub const N_OUTPUTS: u32 = 8;') == 1
    consts.write_text(text.replace('pub const N_OUTPUTS: u32 = 8;', f'pub const N_OUTPUTS: u32 = {n_outputs};'))
    h = m['circuit_hash_u32_le']
    assert len(h) == 8 and all(0 <= w < 2**32 for w in h)
    (work / 'bridge/src/pinned.cairo').write_text(
        '// Generated by build_bridge_arith.py from the trusted client-circuit manifest.\n'
        'use core::box::BoxImpl;\nuse stwo_verifier_core::Hash;\n'
        'use stwo_verifier_core::vcs::blake2s_hasher::Blake2sHash;\n'
        'pub fn circuit_hash() -> Hash {\n    Blake2sHash { hash: BoxImpl::new([' + ', '.join(map(str, h)) + ']) }\n}\n')
    if template == 'cairo-r0':
        # The statement tag (relation and tree format), from the trusted manifest (binding review L1).
        statement_tag = m['statement_tag_u32']
        assert len(statement_tag) == 2 and all(0 < t < 2**31 - 1 for t in statement_tag)
        with (work / 'bridge/src/pinned.cairo').open('a') as f:
            f.write('pub fn statement_tag() -> [u32; 2] {\n    [' + ', '.join(map(str, statement_tag)) + ']\n}\n')
    record = {
        'trusted_manifest_sha256': sha(manifest_path),
        'circuit_hash_u32_le': h,
        'component_log_sizes': logs,
        'fork_commit': fork_commit,
        'vendor_change': 'GENERATED sections of multiverifier_consts.cairo and preprocessed_columns.cairo regenerated by examples/gen_cairo_consts.rs; N_OUTPUTS set from the manifest',
        'message_tag': tag,
        'n_outputs': n_outputs,
        # Filter build output by the path *inside* the crate: the fork itself lives under target/.
        'fork_vendor': {str(p.relative_to(UPSTREAM)): sha(p) for c in CRATES for p in sorted((UPSTREAM / c).rglob('*')) if p.is_file() and 'target' not in p.relative_to(UPSTREAM).parts},
        'template_files': {str(p.relative_to(HERE)): sha(p) for p in sorted((HERE / template).rglob('*')) if p.is_file() and 'target' not in p.parts},
    }
    (work / 'build-record.json').write_text(json.dumps(record, indent=2) + '\n')
    # circuit_hash's own test pins upstream's production constants; the regenerated shape is
    # checked by the layout test here and by the pinned hash at execution.
    for args in (['build', '-p', 'templar_membership_bridge'], ['test', '-p', 'templar_membership_bridge'], ['test', '-p', 'stwo_circuit_air', '--filter', 'hardcoded_component_log_sizes_match_derived']):
        subprocess.run([SCARB, '--manifest-path', str(work / 'Scarb.toml'), *args], check=True)
    subprocess.run([SCARB, '--profile', 'contract', '--manifest-path', str(work / 'Scarb.toml'), 'build', '-p', 'templar_membership_account'], check=True)
    # The sequencer compiles Sierra to CASM with an 80 * 1024-felt bytecode limit; a local OS
    # capture never runs that check (Cairo performance review, Q5).
    casm = next((work / 'target/contract').glob('*.compiled_contract_class.json'))
    sierra = next((work / 'target/contract').glob('*.contract_class.json'))
    n_casm = len(json.loads(casm.read_text())['bytecode'])
    n_sierra = len(json.loads(sierra.read_text())['sierra_program'])
    assert n_casm <= 80 * 1024, f'account CASM {n_casm} felts exceeds the sequencer limit 81920'
    record['account_felts'] = {'sierra': n_sierra, 'casm': n_casm, 'casm_limit': 80 * 1024}
    (work / 'build-record.json').write_text(json.dumps(record, indent=2) + '\n')
    print(json.dumps({'work': str(work), 'circuit_hash_u32_le': h}))


if __name__ == '__main__':
    main()
