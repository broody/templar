"""Build the circuit-A bridge on the unmodified upstream Cairo verifier (proving@5a7c5ed).

Upstream's five verifier crates are copied byte-for-byte; the pinned shape is upstream's own
production `multiverifier_consts.cairo`. The only generated files are ours: circuit A's circuit
hash pin and the statement prefix. Never run this with a manifest from an untrusted producer.
"""
from pathlib import Path
import hashlib, importlib.util, json, shutil, subprocess, sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
UPSTREAM = ROOT / 'target/proving-main/stwo_cairo_verifier/crates'
CRATES = ['bounded_int', 'constraint_framework', 'verifier_core', 'verifier_utils', 'circuit_air']
SCARB = '/home/broody/.asdf/installs/scarb/2.18.0/bin/scarb'
spec = importlib.util.spec_from_file_location('old', HERE / 'build_bridge.py')
old = importlib.util.module_from_spec(spec)
spec.loader.exec_module(old)


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    manifest_path = Path(sys.argv[1]).resolve()
    work = Path(sys.argv[2]).resolve()
    assert not work.exists(), 'fresh work directory required'
    m = json.loads(manifest_path.read_text())
    assert m['purpose'] == 'tmpzk002-client-verifier-circuit' and m['n_outputs'] == 8
    assert m['stack'].startswith('starkware-libs/proving@5a7c5ed')
    shutil.copytree(HERE / 'cairo-proving', work)
    for c in CRATES:
        shutil.copytree(UPSTREAM / c, work / 'vendor' / c, ignore=shutil.ignore_patterns('target'))
    # The only vendor change: circuit_fri_config() blowup 1 -> 2 and queries 70 -> 35 (same
    # 96-bit sum), because 70 queries exceed one virtual block's L2 gas when verified in Cairo.
    consts = work / 'vendor/circuit_air/src/multiverifier_consts.cairo'
    text = consts.read_text()
    fn = text[text.index('pub fn circuit_fri_config()'):]
    fn = fn[:fn.index('}\n}') + 3]
    new = fn.replace('log_blowup_factor: 1,', 'log_blowup_factor: 2,').replace('n_queries: 70,', 'n_queries: 35,')
    assert new.count('log_blowup_factor: 2,') == 1 and new.count('n_queries: 35,') == 1 and new != fn
    text = text.replace(fn, new).replace('26 + 1 * 70 = 96', '26 + 2 * 35 = 96')
    consts.write_text(text)
    assert m['fri_config'] == {'pow_bits': 26, 'log_blowup_factor': 2, 'log_last_layer_degree_bound': 0, 'n_queries': 35, 'fold_step': 4}
    h = m['circuit_hash_u32_le']
    assert len(h) == 8 and all(0 <= w < 2**32 for w in h)
    (work / 'bridge/src/pinned.cairo').write_text(
        '// Generated by build_bridge_proving.py from the trusted circuit-A manifest.\n'
        'use core::box::BoxImpl;\nuse stwo_verifier_core::Hash;\n'
        'use stwo_verifier_core::vcs::blake2s_hasher::Blake2sHash;\n'
        'pub fn circuit_a_hash() -> Hash {\n    Blake2sHash { hash: BoxImpl::new([' + ', '.join(map(str, h)) + ']) }\n}\n')
    prefix = old.statement_prefix()
    (work / 'bridge/src/statement_consts.cairo').write_text(
        '// Generated by build_bridge_proving.py: MAGIC || ro("circuit", client sources).\n'
        'pub fn statement_prefix() -> Array<u8> {\n    array![' + ', '.join(map(str, prefix)) + ']\n}\n')
    record = {
        'trusted_manifest_sha256': sha(manifest_path),
        'circuit_hash_u32_le': h,
        'statement_prefix_hex': prefix.hex(),
        'vendor_change': 'circuit_air/src/multiverifier_consts.cairo circuit_fri_config: log_blowup_factor 1->2, n_queries 70->35',
        'upstream_vendor': {str(p.relative_to(UPSTREAM)): sha(p) for c in CRATES for p in sorted((UPSTREAM / c).rglob('*')) if p.is_file() and 'target' not in p.parts},
        'template_files': {str(p.relative_to(HERE)): sha(p) for p in sorted((HERE / 'cairo-proving').rglob('*')) if p.is_file()},
    }
    (work / 'build-record.json').write_text(json.dumps(record, indent=2) + '\n')
    for args in (['build', '-p', 'templar_membership_bridge'], ['test', '-p', 'templar_membership_bridge']):
        subprocess.run([SCARB, '--manifest-path', str(work / 'Scarb.toml'), *args], check=True)
    subprocess.run([SCARB, '--profile', 'contract', '--manifest-path', str(work / 'Scarb.toml'), 'build', '-p', 'templar_membership_account'], check=True)
    print(json.dumps({'work': str(work), 'circuit_hash_u32_le': h}))


if __name__ == '__main__':
    main()
