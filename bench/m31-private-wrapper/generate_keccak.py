"""Generate an auditable unrolled Keccak round from FIPS202 coordinate rules."""
from pathlib import Path

# Coordinates are x+5*y. rho offsets from FIPS202 table2.
rho = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39, 41, 45, 15, 21, 8, 18, 2, 61, 56, 14]
rc = [0x1, 0x8082, 0x800000000000808A, 0x8000000080008000,
      0x808B, 0x80000001, 0x8000000080008081, 0x8000000000008009,
      0x8A, 0x88, 0x80008009, 0x8000000A, 0x8000808B,
      0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
      0x8000000000008002, 0x8000000000000080, 0x800A,
      0x800000008000000A, 0x8000000080008081, 0x8000000000008080,
      0x80000001, 0x8000000080008008]
lines = ['//! FIPS202 Keccak-f1600; generated by generate_keccak.py.',
         'use core::num::traits::WideMul;',
         'fn rotate(value: u64, multiplier: u64) -> u64 {',
         '    let wide: u128 = value.wide_mul(multiplier);',
         '    let (high, low) = core::integer::u128_safe_divmod(wide, 0x10000000000000000);',
         '    let high: u64 = high.try_into().unwrap();',
         '    let low: u64 = low.try_into().unwrap();',
         '    low | high', '}',
         'fn round(a: Span<u64>, constant: u64) -> Array<u64> {']
for x in range(5):
    lines.append(f'    let c{x} = ' + ' ^ '.join(f'*a.at({x+5*y})' for y in range(5)) + ';')
for x in range(5):
    lines.append(f'    let d{x} = c{(x+4)%5} ^ rotate(c{(x+1)%5}, 2);')
for y in range(5):
    for x in range(5):
        i=x+5*y
        dest=y+5*((2*x+3*y)%5)
        expr=f'(*a.at({i}) ^ d{x})'
        if rho[i]: expr=f'rotate({expr}, {1 << rho[i]})'
        lines.append(f'    let b{dest} = {expr};')
lines.append('    array![')
for y in range(5):
    for x in range(5):
        i=x+5*y
        expr=f'b{i} ^ ((b{(x+1)%5+5*y} ^ 0xffffffffffffffff_u64) & b{(x+2)%5+5*y})'
        if i==0: expr=f'({expr}) ^ constant'
        lines.append(f'        {expr},')
lines += ['    ]', '}', 'pub fn permute(mut state: Array<u64>) -> Array<u64> {',
          '    assert!(state.len() == 25, "KECCAK_STATE");',
          '    let constants: Span<u64> = array![' + ', '.join(hex(c) for c in rc) + '].span();',
          '    for constant in constants { state = round(state.span(), *constant); };',
          '    state', '}']
(Path(__file__).parent/'cairo/src/keccak.cairo').write_text('\n'.join(lines)+'\n')
