"""Known-answer vectors for pool V3's `spend5::compute_binding` (`docs/account-bound-note-spec.md`
§5.2), from the independent Python Poseidon (bench/adr8/ref_poseidon.py). The binding is the one
`client-port/validate_bridge_r5.py` recomputes for every real R0 V5 proof the bridge accepts, with
each delivery digest computed from its ciphertext as the pool does (`spend::delivery_digest`).

Writes `cairo/src/tests/binding_v5_vectors.cairo`. Run from anywhere: `python3 gen_binding_v5_kat.py`.
"""
from pathlib import Path
import importlib.util

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('ref_poseidon', HERE.parent / 'adr8/ref_poseidon.py')
ref = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ref)

P = 2**31 - 1
s = lambda b: int.from_bytes(b, 'big')


def delivery(ct):
    """`spend::delivery_digest`: nine words below 2^248, the last below 2^200."""
    assert len(ct) == 10 and all(w < 2**248 for w in ct[:9]) and ct[9] < 2**200
    return ref.poseidon_hash_span([s(b'CTRL_DELIVERY_V1'), 304, *ct])


def binding(v):
    b = [s(b'TMR0_BIND_V5'), v['chain'], v['pool'], v['asset']]
    b += v['root'] + v['nf'][0] + v['nf'][1]
    for j in range(2):
        b += v['cm'][j] + [delivery(v['ct'][j])]
    b += [v['recipient'], v['amount'], v['intent']] + v['identity'] + [v['valid_until']]
    return ref.poseidon_hash_span(b)


def words(seed):
    return [(seed * 7919 + 104729 * k) % P for k in range(9)]


VECTORS = [
    # A withdrawal of an ERC20 on Sepolia.
    dict(name='withdrawal', chain=s(b'SN_SEPOLIA'), pool=0x7e57b301,
         asset=0x49d36570d4e46f48e99674bd3fcc84644ddd6b96f7c741b1562b82f9e004dc7,
         root=words(1), nf=[words(2), words(3)], cm=[words(4), words(5)],
         ct=[[1000 * k + i + 1 for i in range(10)] for k in (1, 2)],
         recipient=0xb0b, amount=400, intent=0, identity=[0] * 9, valid_until=2600),
    # Extremes: every field at or near its largest value, an intent and an identity.
    dict(name='extremes', chain=s(b'SN_MAIN'), pool=2**251 - 1, asset=2**251 - 1,
         root=[P - 1] * 9, nf=[[P - 1] * 9, [P - 2] * 9], cm=[[P - 1] * 9, [1] * 9],
         ct=[[2**248 - 1] * 9 + [2**200 - 1], [0] * 9 + [1]],
         recipient=2**251 - 1, amount=2**128 - 1, intent=2**251 - 1, identity=[P - 1] * 9,
         valid_until=2**56 - 1),
    # An in-pool transfer: no asset, no withdrawal; the smallest expiry.
    dict(name='transfer', chain=s(b'SN_SEPOLIA'), pool=0x7e57b301, asset=0,
         root=words(11), nf=[words(12), words(13)], cm=[words(14), words(15)],
         ct=[[7 * k + i for i in range(10)] for k in (3, 4)],
         recipient=0, amount=0, intent=0, identity=[0] * 9, valid_until=1),
]


def span(xs):
    return 'array![' + ', '.join(hex(x) for x in xs) + '].span()'


def main():
    out = ['// Generated by bench/m31-pool/gen_binding_v5_kat.py: `TMR0_BIND_V5` from the Python Poseidon.',
           'use m31_pool::spend::{Output, Withdrawal};',
           'use m31_pool::spend5::Spend;',
           '',
           '/// `(name, spend with its expected binding)`.',
           'pub fn vectors() -> Array<(felt252, Spend)> {',
           '    array![']
    for v in VECTORS:
        outputs = ', '.join(f'Output {{ commitment: {span(v["cm"][j])}, ciphertext: {span(v["ct"][j])} }}' for j in range(2))
        out += [f"        ('{v['name']}', Spend {{",
                f"            chain: {hex(v['chain'])}, pool: {hex(v['pool'])}.try_into().unwrap(), asset: {hex(v['asset'])},",
                f"            root: {span(v['root'])},",
                f"            nullifiers: {span(v['nf'][0] + v['nf'][1])},",
                f"            outputs: array![{outputs}].span(),",
                f"            withdrawal: Withdrawal {{ recipient: {hex(v['recipient'])}.try_into().unwrap(), amount: {hex(v['amount'])} }},",
                f"            intent: {hex(v['intent'])}, identity: {span(v['identity'])}, valid_until: {hex(v['valid_until'])},",
                f"            binding: {hex(binding(v))},",
                '        }),']
    out += ['    ]', '}', '']
    path = HERE / 'cairo/src/tests/binding_v5_vectors.cairo'
    path.write_text('\n'.join(out))
    print(path)


if __name__ == '__main__':
    main()
