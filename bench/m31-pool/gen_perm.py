def arr(name):
    body=src[src.index('pub const '+name):]
    body=body[body.index('= ')+2:]
    depth=0; end=0
    for i,ch in enumerate(body):
        if ch=='[': depth+=1
        elif ch==']':
            depth-=1
            if depth==0: end=i; break
    return [int(x,16) for x in re.findall(r'0x[0-9a-fA-F]+', body[:end])]
EI=arr('EXTERNAL_INITIAL'); EF=arr('EXTERNAL_FINAL'); IN=arr('INTERNAL')
assert len(EI)==96 and len(EF)==96 and len(IN)==22
P=2**31-1
def external(s):
    s=list(s)
    for off in range(0,24,4):
        x=s[off:off+4]; mat=[[2,3,1,1],[1,2,3,1],[1,1,2,3],[3,1,1,2]]
        for i in range(4): s[off+i]=sum(x[j]*mat[i][j] for j in range(4))%P
    sums=[sum(s[i+k] for i in range(0,24,4))%P for k in range(4)]
    return [(s[i]+sums[i%4])%P for i in range(24)]
def internal(s):
    t=sum(s)%P
    return [(t+s[i]*((P-2) if i==0 else (1<<(i-1))))%P for i in range(24)]
def perm(s):
    s=external(s)
    for r in range(4):
        s=[pow((s[i]+EI[r*24+i])%P,5,P) for i in range(24)]; s=external(s)
    for r in range(22):
        s[0]=pow((s[0]+IN[r])%P,5,P); s=internal(s)
    for r in range(4):
        s=[pow((s[i]+EF[r*24+i])%P,5,P) for i in range(24)]; s=external(s)
    return s
