"""Generate cairo/src/zeros.cairo and cairo/src/tests/vectors.cairo from vectors.json
(client-port examples/pool_vectors.rs) and the spend binding reference
(client-port validate_bridge_r0.binding)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
v = json.loads((HERE / 'vectors.json').read_text())


def arr(d):
    return '[' + ', '.join(str(x) for x in d) + ']'


z = ['//! Generated by gen_cairo.py from vectors.json: empty-subtree digests Z_0..Z_32 per node format.',
     'use crate::hash::{COMPRESS, Digest};', '',
     'pub fn zero(format: u8, level: u32) -> Digest {',
     '    if format == COMPRESS {', '        match level {']
for i, d in enumerate(v['formats']['Compress']['zeros']):
    z.append(f'            {i} => {arr(d)},' if i < 32 else f'            _ => {arr(d)},')
z += ['        }', '    } else {', '        match level {']
for i, d in enumerate(v['formats']['Sponge']['zeros']):
    z.append(f'            {i} => {arr(d)},' if i < 32 else f'            _ => {arr(d)},')
z += ['        }', '    }', '}', '']
(HERE / 'cairo/src/zeros.cairo').write_text('\n'.join(z))

t = ['//! Generated by gen_cairo.py from vectors.json (client-port examples/pool_vectors.rs).', '']
t.append(f"pub const PERM_IN: [felt252; 24] = {arr(v['permutation']['input'])};")
t.append(f"pub const PERM_OUT: [felt252; 24] = {arr(v['permutation']['output'])};")
t.append('pub fn leaves() -> Array<[felt252; 9]> {\n    array![' + ', '.join(arr(l) for l in v['leaves']) + ']\n}')
for name in ('Sponge', 'Compress'):
    roots = v['formats'][name]['roots']
    t.append(f'pub fn roots_{name.lower()}() -> Array<[felt252; 9]> {{\n    array![' + ', '.join(arr(r) for r in roots) + ']\n}')
    t.append(f"pub const EMPTY_ROOT_{name.upper()}: [felt252; 9] = {arr(v['formats'][name]['zeros'][32])};")
d = v['deposit']
t.append(f"pub const DEPOSIT_CHAIN: felt252 = {d['chain']};")
t.append(f"pub const DEPOSIT_POOL: felt252 = {d['pool']};")
t.append(f"pub const DEPOSIT_TOKEN: felt252 = {d['token']};")
t.append(f"pub const DEPOSIT_AMOUNT: u128 = {d['amount']};")
t.append(f"pub const DEPOSIT_INNER: [felt252; 9] = {arr(d['inner'])};")
t.append(f"pub const DEPOSIT_CM: [felt252; 9] = {arr(d['commitment'])};")
(HERE / 'cairo/src/tests/vectors.cairo').write_text('\n'.join(t) + '\n')
print('generated')
