"""The routing adapter's encoding vectors (`docs/pool-v3-spec.md` §6.1), shared by the Cairo
adapter tests, the prover server and the SDK: a `Route`'s eight felts in Serde order, `Option<Route>`
(`Some` is `0` then the route, `None` is `1`), a two-route `get_routes()` array and a
`get_route_proposals()` array with one addition and one removal.

Writes `sdk/vectors/routing.json` and `bench/m31-pool/cairo/src/tests/routing_vectors.cairo`.

    python3 bench/m31-pool/gen_routing_vectors.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OS = 0x53f6c9fcfd31d27279ff7d7e422b44623550a732b59fe193354a7316a96daa1


def short(s):
    assert len(s) <= 31 and s.isascii()
    return int.from_bytes(s.encode(), 'big')


ROUTES = {
    'r0_v6': {'statement': 0x5a7e, 'statement_class': 0xc1a5, 'account_tag': 'TMPZR0_PAYMENT_V6', 'os_program': OS,
              'proof_version': 'PROOF2', 'proof_variant': 'VIRTUAL_SNOS', 'output_version': 'VIRTUAL_SNOS0', 'max_proof_age': 1024},
    'p1_v1': {'statement': 0x052828eb2a0d2095a0fa70d514b08a6ae4a2cb1ec38f72d2d843f1bf2a12d70a,
              'statement_class': 0x032e05ae1fc0e76252f356e169d2a896b0befea4adca4a8d653c0f107836a882,
              'account_tag': 'TMPZP1_POLICY_V1', 'os_program': OS + 1, 'proof_version': 'PROOF2',
              'proof_variant': 'VIRTUAL_SNOS', 'output_version': 'VIRTUAL_SNOS0', 'max_proof_age': 1600},
}


def felts(r):
    return [r['statement'], r['statement_class'], short(r['account_tag']), r['os_program'], short(r['proof_version']),
            short(r['proof_variant']), short(r['output_version']), r['max_proof_age']]


a, b = ROUTES['r0_v6'], ROUTES['p1_v1']
PROPOSALS = [{'statement': b['statement'], 'route': 'p1_v1', 'eta': 1_000_000 + 7200},
             {'statement': a['statement'], 'route': None, 'eta': 1_003_600}]
get_routes = [2] + felts(a) + felts(b)
get_route_proposals = [2, b['statement'], 0] + felts(b) + [1_007_200, a['statement'], 1, 1_003_600]

hexs = lambda xs: [hex(x) for x in xs]
doc = {
    'scope': 'Routing adapter encodings (pool-v3-spec §6.1); generated by bench/m31-pool/gen_routing_vectors.py',
    'routes': {k: {**{f: (hex(v) if isinstance(v, int) and f != 'max_proof_age' else v) for f, v in r.items()}, 'felts': hexs(felts(r))}
               for k, r in ROUTES.items()},
    'some_r0_v6': hexs([0] + felts(a)),
    'none': hexs([1]),
    'get_routes': {'routes': ['r0_v6', 'p1_v1'], 'felts': hexs(get_routes)},
    'get_route_proposals': {'proposals': [{**p, 'statement': hex(p['statement'])} for p in PROPOSALS], 'felts': hexs(get_route_proposals)},
}
(ROOT / 'sdk/vectors/routing.json').write_text(json.dumps(doc, indent=1) + '\n')


def cairo_route(r):
    return (f"Route {{ statement: {hex(r['statement'])}.try_into().unwrap(), statement_class: {hex(r['statement_class'])}, "
            f"account_tag: '{r['account_tag']}', os_program: {hex(r['os_program'])}, proof_version: '{r['proof_version']}', "
            f"proof_variant: '{r['proof_variant']}', output_version: '{r['output_version']}', max_proof_age: {r['max_proof_age']} }}")


arr = lambda xs: 'array![' + ', '.join(hex(x) for x in xs) + ']'
cairo = f"""// Generated by bench/m31-pool/gen_routing_vectors.py (the same vectors as sdk/vectors/routing.json).
// Do not edit.
use m31_pool::routing_adapter::{{Route, RouteProposal}};

pub fn r0_v6() -> Route {{
    {cairo_route(a)}
}}
pub fn p1_v1() -> Route {{
    {cairo_route(b)}
}}
pub fn proposals() -> Array<RouteProposal> {{
    array![
        RouteProposal {{ statement: {hex(b['statement'])}.try_into().unwrap(), route: Option::Some(p1_v1()), eta: 1007200 }},
        RouteProposal {{ statement: {hex(a['statement'])}.try_into().unwrap(), route: Option::None, eta: 1003600 }},
    ]
}}
pub fn r0_v6_felts() -> Array<felt252> {{
    {arr(felts(a))}
}}
pub fn some_r0_v6_felts() -> Array<felt252> {{
    {arr([0] + felts(a))}
}}
pub fn get_routes_felts() -> Array<felt252> {{
    {arr(get_routes)}
}}
pub fn get_route_proposals_felts() -> Array<felt252> {{
    {arr(get_route_proposals)}
}}
"""
(ROOT / 'bench/m31-pool/cairo/src/tests/routing_vectors.cairo').write_text(cairo)
print('wrote sdk/vectors/routing.json and cairo/src/tests/routing_vectors.cairo')
