#!/usr/bin/env python3
"""Generate the two topology-specific vendor files from a trusted synthetic manifest.

Input is a build artifact from the fixed client circuit, never proof-supplied runtime
configuration. The generator checks every column identity, component size, and public
address. vendor-source.json retains hashes of the pristine upstream files; this writes
generated-config.json recording the only intended vendor deviations.
"""
import argparse
import hashlib
import json
from pathlib import Path

BASE = Path(__file__).resolve().parent
SYMBOLS = {
    "eq_in0_address": "EQ_IN0_ADDRESS_IDX",
    "eq_in1_address": "EQ_IN1_ADDRESS_IDX",
    "qm31_ops_add_flag": "ADD_FLAG_IDX",
    "qm31_ops_sub_flag": "SUB_FLAG_IDX",
    "qm31_ops_mul_flag": "MUL_FLAG_IDX",
    "qm31_ops_pointwise_mul_flag": "POINTWISE_MUL_FLAG_IDX",
    "qm31_ops_in0_address": "OP_0_ADDR_IDX",
    "qm31_ops_in1_address": "OP_1_ADDR_IDX",
    "qm31_ops_out_address": "DST_ADDR_IDX",
    "qm31_ops_mults": "QM_31_OPS_MULTIPLICITY_IDX",
    "seq_16": "SEQ_16_IDX",
}
for name in ["input_addr_0", "input_addr_1", "input_addr_2", "output_addr", "multiplicity"]:
    SYMBOLS[f"triple_xor_{name}"] = f"TRIPLE_XOR_{name.upper()}_IDX"
for name in ["input_addr", "output_addr", "multiplicity"]:
    SYMBOLS[f"m31_to_u32_{name}"] = f"M_31_TO_U_32_{name.upper()}_IDX"
for name in ["input_addr_a", "input_addr_b", "input_addr_c", "input_addr_d",
             "input_addr_f0", "input_addr_f1", "output_addr_a", "output_addr_b",
             "output_addr_c", "output_addr_d", "multiplicity"]:
    suffix = name.upper().replace("F0", "F_0").replace("F1", "F_1")
    SYMBOLS[f"blake_g_gate_{name}"] = f"BLAKE_G_GATE_{suffix}_IDX"
for bits in [4, 7, 8, 9, 10]:
    for coordinate in range(3):
        SYMBOLS[f"bitwise_xor_{bits}_{coordinate}"] = (
            f"BITWISE_XOR_{12 if bits == 10 else bits}_{coordinate}_IDX"
        )


def generate(manifest):
    assert manifest["purpose"] == "synthetic-diagnostic"
    assert manifest["channel"] == "Blake2sMerkleChannel"
    assert manifest["merkle_hasher"] == "Blake2sMerkleHasher"
    cols = manifest["preprocessed_columns"]
    names = [c["id"] for c in cols]
    assert len(cols) == len(SYMBOLS) == len(set(names)) == 45
    assert set(names) == set(SYMBOLS), (set(names) - set(SYMBOLS), set(SYMBOLS) - set(names))
    sizes = [c["log_size"] for c in cols]
    assert all(type(n) is int and 1 <= n <= 30 for n in sizes)
    assert sizes == sorted(sizes), "client must supply the stable size-sorted column order"
    logs = dict(zip(names, sizes))
    component_names = ["eq_in0_address", "qm31_ops_in0_address", "triple_xor_input_addr_0",
                       "m31_to_u32_input_addr", "blake_g_gate_input_addr_a"]
    derived_sizes = [logs[name] for name in component_names] + [16, 20, 8, 14, 18, 16]
    assert manifest["component_log_sizes"] == derived_sizes
    for prefix, expected in [("eq_", derived_sizes[0]), ("qm31_ops_", derived_sizes[1]),
                             ("triple_xor_", derived_sizes[2]), ("m31_to_u32_", derived_sizes[3]),
                             ("blake_g_gate_", derived_sizes[4]), ("seq_", 16)]:
        assert all(size == expected for name, size in logs.items() if name.startswith(prefix))
    for bits in [4, 7, 8, 9, 10]:
        assert all(logs[f"bitwise_xor_{bits}_{i}"] == bits * 2 for i in range(3))
    config = manifest["pcs_config"]
    fri = config["fri_config"]
    assert config["pow_bits"] == 26
    assert fri == {"log_blowup_factor": 2, "log_last_layer_degree_bound": 0,
                   "n_queries": 35, "fold_step": 4}
    lifting = config["lifting_log_size"]
    assert lifting == max(derived_sizes) + fri["log_blowup_factor"]
    addresses = manifest["output_addresses"]
    assert addresses == list(range(3, 3 + len(addresses)))
    assert manifest["u_address"] == 2
    root = manifest["preprocessed_root_u32_le"]
    assert len(root) == 8 and all(type(x) is int and 0 <= x < 2**32 for x in root)
    preamble = "// Generated by generate_constants.py from a trusted synthetic circuit manifest.\n"
    indices = preamble + "use stwo_constraint_framework::{INVALID_COLUMN_IDX, PreprocessedColumnIdx};\n"
    indices += "pub const NUM_PREPROCESSED_COLUMNS: u32 = 45;\n"
    for idx, name in enumerate(names):
        indices += f"// {name}, log_size={logs[name]}\n"
        indices += f"pub const {SYMBOLS[name]}: PreprocessedColumnIdx = {idx};\n"
    indices += """
const INVALID_IDX_CHECK: () = if NUM_PREPROCESSED_COLUMNS >= INVALID_COLUMN_IDX {
    core::panic_with_felt252('invalid idx too small')
};
pub fn seq_column_idx(log_size: u32) -> PreprocessedColumnIdx {
    match log_size {
        16 => SEQ_16_IDX,
        _ => panic!("unsupported seq column log_size"),
    }
}
"""
    constants = preamble + """use core::box::BoxImpl;
use stwo_verifier_core::Hash;
use stwo_verifier_core::fri::FriConfig;
use stwo_verifier_core::pcs::PcsConfig;
use stwo_verifier_core::vcs::blake2s_hasher::Blake2sHash;
"""
    constants += f"pub const LIFTING_LOG_SIZE: u32 = {lifting};\n"
    constants += f"pub const N_OUTPUTS: u32 = {len(addresses)};\n"
    constants += """pub fn circuit_pcs_config() -> PcsConfig {
    PcsConfig {
        pow_bits: 26,
        fri_config: FriConfig {
            log_blowup_factor: 2, log_last_layer_degree_bound: 0, n_queries: 35, fold_step: 4,
        },
        lifting_log_size: Some(LIFTING_LOG_SIZE),
    }
}
pub const PREPROCESSED_COLUMN_LOG_SIZES: [u32; 45] = [
"""
    constants += "".join(f"    {logs[name]}, // {name}\n" for name in names) + "];\n"
    constants += "pub fn preprocessed_root() -> Hash {\n    Blake2sHash { hash: BoxImpl::new(["
    constants += ", ".join(map(str, root)) + "]) }\n}\n"
    return {"circuit_air/src/preprocessed_columns.cairo": indices,
            "circuit_air/src/privacy_consts.cairo": constants}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path)
    args = parser.parse_args()
    raw = args.manifest.read_bytes()
    manifest = json.loads(raw)
    changes = generate(manifest)
    for name, source in changes.items():
        (BASE / "vendor" / name).write_text(source)
    record = {"manifest_path": str(args.manifest.resolve()),
              "manifest_sha256": hashlib.sha256(raw).hexdigest(),
              "manifest": manifest,
              "changed_vendor_files_sha256": {
                  name: hashlib.sha256(text.encode()).hexdigest() for name, text in changes.items()
              }}
    (BASE / "generated-config.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps({"generated": list(changes), "manifest_sha256": record["manifest_sha256"]}))


if __name__ == "__main__":
    main()
